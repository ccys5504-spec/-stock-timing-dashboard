            "동시에 신호를 냈는지)와 **기준일**(이 신호를 계산한 마지막 "
            "거래일)이 같이 표시됩니다.\n"
            "- **📊 3종목 비교**: 관심종목 3개의 배지를 한 화면에서 동시에 "
            "볼 수 있습니다.\n"
            "- **🧭 종목 추천(스크리너)**: 관심종목 3개에 국한하지 않고, "
            "시가총액 상위 종목들을 훑어서 지금 매수/매도 신호가 뜬 종목을 "
